using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace Podish.PerfTools;

internal static partial class Program
{
    private static string GenerateSuperopcodeSequences(string input, JsonElement data, int top)
    {
        var patterns = new List<string[]>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var candidate in data.GetProperty("candidates").EnumerateArray())
        {
            var ops = candidate.GetProperty("pair").EnumerateArray().Select(element => CanonicalLogicName(element.GetString() ?? "")).ToArray();
            if (ops.Length is < 2 or > 4 || ops.Any(op => !Regex.IsMatch(op, @"^op::Op[A-Za-z0-9_]+$")))
                throw new InvalidDataException("Generated sequences require 2..4 valid handler names");
            if (seen.Add(string.Join('\t', ops))) patterns.Add(ops);
            if (patterns.Count == top) break;
        }
        if (patterns.Count == 0) throw new InvalidDataException("Cannot generate empty sequence table");
        // Bake semantic specializations as separate exact-match sequences.
        // Keep original handlers for memory forms and execute specialized logic in
        // the new variants; do not normalize back to generic logic at runtime.
        var selectedPatternCount = patterns.Count;
        var specializationFamilies = new Dictionary<string, string[]>(StringComparer.Ordinal)
        {
            ["op::OpAdd_EvGv"] = ["op::OpAdd_EvGv_Eax"],
            ["op::OpGroup2_EvIb_Shl"] = ["op::OpGroup2_EvIb_Shl_ModReg"],
            ["op::OpGroup2_Ev1_Shl"] = ["op::OpGroup2_Ev1_Shl_ModReg"],
            ["op::OpGroup2_EvCl_Shl"] = ["op::OpGroup2_EvCl_Shl_ModReg"],
            ["op::OpGroup2_EvIb_Shr"] = ["op::OpGroup2_EvIb_Shr_ModReg"],
            ["op::OpGroup2_Ev1_Shr"] = ["op::OpGroup2_Ev1_Shr_ModReg"],
            ["op::OpGroup2_EvCl_Shr"] = ["op::OpGroup2_EvCl_Shr_ModReg"],
            ["op::OpGroup2_EvIb_Sar"] = ["op::OpGroup2_EvIb_Sar_ModReg"],
            ["op::OpGroup2_Ev1_Sar"] = ["op::OpGroup2_Ev1_Sar_ModReg"],
            ["op::OpGroup2_EvCl_Sar"] = ["op::OpGroup2_EvCl_Sar_ModReg"]
        };
        foreach (var pattern in patterns.Take(selectedPatternCount).ToArray())
        {
            var variants = new List<string[]> { Array.Empty<string>() };
            foreach (var op in pattern)
            {
                var choices = specializationFamilies.TryGetValue(op, out var family)
                    ? new[] { op }.Concat(family).ToArray() : new[] { op };
                variants = variants.SelectMany(prefix => choices.Select(choice => prefix.Append(choice).ToArray())).ToList();
            }
            foreach (var variant in variants)
                if (seen.Add(string.Join('\t', variant))) patterns.Add(variant);
        }
        string Name(int index) => $"SuperOpcode_{patterns[index].Length}_{index:000}_" +
                                  string.Join("__", patterns[index].Select(op => SanitizeName(op[4..])));
        var builder = new StringBuilder();
        builder.AppendLine("// Generated by Podish.PerfTools; exact 2..4-op matching, longest first.");
        builder.AppendLine("// source_sha256=" + TrainingHash(input));
        builder.AppendLine("// selected_pattern_count=" + selectedPatternCount);
        builder.AppendLine("// specialization_expansion_count=" + (patterns.Count - selectedPatternCount));
        builder.AppendLine("// generated_pattern_count=" + patterns.Count);
        builder.AppendLine("#include <ankerl/unordered_dense.h>\n#include <atomic>\n#include <array>\n#include <cstdint>\n#include <vector>");
        builder.AppendLine("#include \"superopcodes.h\"\n#include \"ops.h\"");
        foreach (var file in Directory.EnumerateFiles(Path.Combine(RepoRoot(), "libfibercpu", "src", "ops"), "*_impl.h").Order(StringComparer.Ordinal))
            builder.AppendLine($"#include \"ops/{Path.GetFileName(file)}\"");
        builder.AppendLine("""
            namespace fiberish {
            namespace {
            struct GeneratedSequenceKey {
                HandlerFunc first, second;
                bool operator==(const GeneratedSequenceKey&) const = default;
            };
            struct GeneratedSequenceHash {
                uint64_t operator()(const GeneratedSequenceKey& key) const {
                    uint64_t a = static_cast<uint64_t>(reinterpret_cast<uintptr_t>(key.first));
                    uint64_t b = static_cast<uint64_t>(reinterpret_cast<uintptr_t>(key.second));
                    return (a >> 2) ^ ((b >> 2) * 0x9e3779b97f4a7c15ULL);
                }
            };
            struct GeneratedSequenceMatch { HandlerFunc third, fourth, fused; uint8_t width; };
            using GeneratedSequenceMap = ankerl::unordered_dense::map<GeneratedSequenceKey,
                std::vector<GeneratedSequenceMatch>, GeneratedSequenceHash>;
            struct GeneratedSequenceTable : GeneratedSequenceMap { std::array<uint64_t, 16> bits{}; };
            } // namespace
            """);
        for (var index = 0; index < patterns.Count; index++)
        {
            builder.AppendLine($"ATTR_PRESERVE_NONE int64_t {Name(index)}(EmuState* RESTRICT state, DecodedOp* RESTRICT op,");
            builder.AppendLine("    int64_t instr_limit, mem::MicroTlbAbiWord utlb_tags, mem::MicroTlbAbiWord utlb_addend,");
            builder.AppendLine("    uint32_t branch, uint64_t flags_cache) {");
            builder.AppendLine("    mem::MicroTLB utlb = mem::DecodeMicroTlbAbi(utlb_tags, utlb_addend);");
            for (var position = 0; position < patterns[index].Length; position++)
            {
                builder.AppendLine(position == 0 ? "    DecodedOp* constituent0 = op;" :
                    $"    DecodedOp* constituent{position} = NextOp(constituent{position - 1});");
                builder.AppendLine($"    RUN_SUPEROPCODE_OP({patterns[index][position]}, state, constituent{position}, instr_limit, utlb, branch, flags_cache);");
            }
            builder.AppendLine($"    if (auto* next = NextOp(constituent{patterns[index].Length - 1})) {{");
            builder.AppendLine("        mem::EncodeMicroTlbAbi(utlb, utlb_tags, utlb_addend);");
            builder.AppendLine("        ATTR_MUSTTAIL return next->handler(state, next, instr_limit, utlb_tags, utlb_addend, branch, flags_cache);");
            builder.AppendLine("    }\n    __builtin_unreachable();\n}");
        }
        builder.AppendLine("namespace {\nGeneratedSequenceTable* BuildGeneratedSequenceTable() {\n    auto* table = new GeneratedSequenceTable();");
        var groups = Enumerable.Range(0, patterns.Count).GroupBy(index => patterns[index][0] + "\t" + patterns[index][1], StringComparer.Ordinal).ToArray();
        builder.AppendLine($"    table->reserve({groups.Length});");
        foreach (var group in groups)
        {
            var prefix = patterns[group.First()];
            builder.AppendLine($"    table->emplace(GeneratedSequenceKey{{(HandlerFunc)DispatchWrapper<{prefix[0]}>, (HandlerFunc)DispatchWrapper<{prefix[1]}>}},");
            builder.AppendLine("        std::vector<GeneratedSequenceMatch>{");
            foreach (var index in group.OrderByDescending(index => patterns[index].Length).ThenBy(index => index))
            {
                var ops = patterns[index];
                var third = ops.Length >= 3 ? $"(HandlerFunc)DispatchWrapper<{ops[2]}>" : "nullptr";
                var fourth = ops.Length == 4 ? $"(HandlerFunc)DispatchWrapper<{ops[3]}>" : "nullptr";
                builder.AppendLine($"            GeneratedSequenceMatch{{{third}, {fourth}, {Name(index)}, {ops.Length}}},");
            }
            builder.AppendLine("        });");
        }
        builder.AppendLine("    for (const auto& entry : *table) {\n        auto hash = GeneratedSequenceHash{}(entry.first);\n        table->bits[(hash >> 6) & 15] |= uint64_t{1} << (hash & 63);\n    }\n    return table;\n}\n} // namespace");
        builder.AppendLine("""
            __attribute__((used)) HandlerFunc GeneratedFindSuperOpcode(const DecodedOp* ops) {
                if (!ops) return nullptr;
                static std::atomic<GeneratedSequenceTable*> table_ptr{nullptr};
                auto* table = table_ptr.load(std::memory_order_acquire);
                if (!table) {
                    auto* created = BuildGeneratedSequenceTable();
                    auto* expected = static_cast<GeneratedSequenceTable*>(nullptr);
                    if (!table_ptr.compare_exchange_strong(expected, created, std::memory_order_acq_rel, std::memory_order_acquire)) {
                        delete created;
                        table = expected;
                    } else table = created;
                }
                const auto* second = NextOp(ops);
                GeneratedSequenceKey key{ops->handler, second->handler};
                auto hash = GeneratedSequenceHash{}(key);
                if (!(table->bits[(hash >> 6) & 15] & (uint64_t{1} << (hash & 63)))) return nullptr;
                auto entry = table->find(key);
                if (entry == table->end()) return nullptr;
                for (const auto& match : entry->second) {
                    if (match.width == 2) return match.fused;
                    const auto* third = NextOp(second);
                    if (third->len == 0 || third->handler != match.third) continue;
                    if (match.width == 3) return match.fused;
                    const auto* fourth = NextOp(third);
                    if (fourth->len != 0 && fourth->handler == match.fourth) return match.fused;
                }
                return nullptr;
            }
            #ifdef FIBERCPU_VALIDATE_SPECIALIZATION_INDEX
            bool ValidateGeneratedSequenceLookup() {
                auto* table = BuildGeneratedSequenceTable();
                auto verify = [&](DecodedOp* ops) {
                    HandlerFunc expected = nullptr;
                    auto it = table->find({ops[0].handler, ops[1].handler});
                    if (it != table->end()) {
                        for (const auto& match : it->second) {
                            if (match.width == 2 ||
                                (ops[2].len && ops[2].handler == match.third &&
                                 (match.width == 3 || (ops[3].len && ops[3].handler == match.fourth)))) {
                                expected = match.fused;
                                break;
                            }
                        }
                    }
                    return GeneratedFindSuperOpcode(ops) == expected;
                };
                bool ok = true;
                for (const auto& entry : *table) {
                    DecodedOp ops[4]{};
                    ops[0].handler = entry.first.first;
                    ops[1].handler = entry.first.second;
                    for (const auto& match : entry.second) {
                        ops[2].handler = match.third;
                        ops[3].handler = match.fourth;
                        for (int lengths = 0; lengths < 4; ++lengths) {
                            ops[2].len = lengths & 1;
                            ops[3].len = (lengths >> 1) & 1;
                            if (!verify(ops)) ok = false;
                        }
                    }
                    for (const auto& other : *table) {
                        ops[1].handler = other.first.second;
                        ops[2].len = ops[3].len = 0;
                        if (!verify(ops)) ok = false;
                    }
                }
                delete table;
                return ok;
            }
            #endif
            } // namespace fiberish
            """);
        return builder.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
    }
}
