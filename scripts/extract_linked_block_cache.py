#!/usr/bin/env python3
"""Extract the native objects and exact recipe index for a linked block cache."""

import argparse
import struct
from pathlib import Path


from gen_instruction_catalog import CATALOG, llvm_operation_fingerprint, llvm_operation_names, read_catalog


MAGIC = b"FIBJLC05"
MACHO_ARM64_OBJECT = (0xFEEDFACF, 0x0100000C, 0, 1)


def read_record(data, pos):
    if len(data) - pos < 4:
        raise ValueError("truncated cache record size")
    size, = struct.unpack_from("<I", data, pos)
    start = pos + 4
    if not size or size > len(data) - start:
        raise ValueError("invalid cache record size")
    return data[start:start + size], start + size


def read_key(record, operation_count):
    if len(record) < 3:
        raise ValueError("truncated linked cache key")
    exit_kind, exact, count = record[:3]
    if exit_kind > 2 or exact != 1 or not 1 <= count <= 64 or len(record) != 3 + 28 * count:
        raise ValueError("invalid linked cache key header")
    steps = tuple(struct.iter_unpack("<HBB6I", record[3:]))
    operations = tuple(step[:3] for step in steps)
    if any(op >= operation_count or slots not in (1, 2) for op, _, slots in operations):
        raise ValueError("linked cache refers to an unknown operation ID")
    operands = tuple(step[3:7] for step in steps)
    eips = tuple(step[7:] for step in steps)
    if any(width > 3 for _, width in eips):
        raise ValueError("linked cache has an invalid relative branch width")
    return exit_kind, exact, operations, operands, eips


def read_region(record, operation_count):
    members = []
    pos = 1
    while pos < len(record):
        if len(record) - pos < 4:
            raise ValueError("truncated linked page member")
        offset, = struct.unpack_from("<I", record, pos)
        if offset >= 4096 or (members and offset <= members[-1][0]):
            raise ValueError("invalid linked page member offset")
        key, pos = read_record(record, pos + 4)
        key = read_key(key, operation_count)
        if key[0] == 0:
            raise ValueError("linked page member needs a complete block recipe")
        members.append((offset, key))
    if not 2 <= len(members) <= 12:
        raise ValueError("invalid member count for linked page")
    return members


def read_bundle(path, abi, op_names):
    data = path.read_bytes()
    if not data.startswith(MAGIC):
        raise ValueError("expected a version 5 linked cache; regenerate it with fibercpu_llvm_cache --linked")
    start = len(MAGIC)
    end = start + len(abi)
    if data[start:end] != abi.encode("ascii"):
        raise ValueError("linked cache ABI differs from this build; retrain with the same sources and settings")
    fingerprint = llvm_operation_fingerprint(op_names).encode("ascii")
    if data[end:end + len(fingerprint)] != fingerprint:
        raise ValueError("linked cache LLVM operation IDs differ from this build")
    cpu, pos = read_record(data, end + len(fingerprint))
    if any(value < 0x20 or value > 0x7e for value in cpu) or len(cpu) >= 128:
        raise ValueError("invalid linked cache host CPU")
    entries = {}
    regions = []
    objects = []
    while pos < len(data):
        record, pos = read_record(data, pos)
        obj, pos = read_record(data, pos)
        if len(obj) < 32 or struct.unpack_from("<4I", obj) != MACHO_ARM64_OBJECT:
            raise ValueError("expected a native macOS ARM64 relocatable object")
        index = len(objects)
        objects.append(obj)
        if record[0] == 0xff:
            regions.append((index, read_region(record, len(op_names))))
        else:
            key = read_key(record, len(op_names))
            if key in entries:
                raise ValueError("duplicate linked cache key")
            entries[key] = index
    if not objects:
        raise ValueError("linked cache contains no blocks")
    return cpu, entries, regions, objects


def literal(data):
    return '"' + "".join(f"\\x{byte:02x}" for byte in data) + '"'


def write_build_inputs(output, cpu, entries, regions, objects):
    output.mkdir(parents=True, exist_ok=True)
    table = ["// Generated by extract_linked_block_cache.py.",
             f"constexpr std::string_view linked_cache_cpu = {literal(cpu)};"]
    for index, obj in enumerate(objects):
        (output / f"block_{index}.o").write_bytes(obj)
    for index in entries.values():
        table.append(f'extern "C" std::remove_pointer_t<HandlerFunc> FiberCachedBlock_{index};')
    for index, members in regions:
        for ordinal in range(len(members)):
            table.append(f'extern "C" std::remove_pointer_t<HandlerFunc> FiberCachedPage_{index}_{ordinal};')
    keys = sorted(entries.keys() | {key for _, members in regions for _, key in members})
    key_order = {key: i for i, key in enumerate(keys)}
    operations = ["constexpr block_recipe::BoundOperation linked_cache_operations[] = {"]
    operands = ["constexpr DecodedOperandShape linked_cache_operands[] = {"]
    eips = ["constexpr block_recipe::StepEip linked_cache_eips[] = {"]
    recipes = ["constexpr block_recipe::BlockKeyView linked_cache_keys[] = {"]
    offset = 0
    for exit_kind, _, ops, shapes, steps in keys:
        operations.append("    " + ", ".join(f"{{block_recipe::OpId{{{op}}}, {{{modrm}, {slots}}}}}" for op, modrm, slots in ops) + ",")
        for shape in shapes:
            operands.append("    {" + ", ".join(f"0x{field:08x}u" for field in shape) + "},")
        for next_offset, width in steps:
            eips.append(f"    {{0x{next_offset:08x}u, {width}}},")
        count = len(ops)
        recipes.append(f"    {{LLVMBlockExit{{{exit_kind}}}, {{linked_cache_operations + {offset}, {count}}}, "
                       f"{{linked_cache_operands + {offset}, {count}}}, "
                       f"{{linked_cache_eips + {offset}, {count}}}}},")
        offset += count
    for block in (operations, operands, eips, recipes):
        table.extend([*block, "};", ""])
    table.append(f"constexpr std::array<LinkedBlockEntry, {len(entries)}> linked_cache_entries = {{{{")
    for key, index in sorted(entries.items()):
        table.append(f"    {{linked_cache_keys[{key_order[key]}], FiberCachedBlock_{index}}},")
    table.extend(["}};", ""])
    if regions:
        table.append("constexpr LinkedPageMember linked_page_members[] = {")
        for index, members in regions:
            for ordinal, (offset, key) in enumerate(members):
                table.append(f"    {{&linked_cache_keys[{key_order[key]}], FiberCachedPage_{index}_{ordinal}, {offset}}},")
        table.extend(["};", ""])
    table.append(f"constexpr std::array<LinkedPageRegion, {len(regions)}> linked_page_regions = {{{{")
    position = 0
    for _, members in regions:
        table.append(f"    {{{{linked_page_members + {position}, {len(members)}}}}},")
        position += len(members)
    table.append("}};")
    (output / "linked_block_cache.inc").write_text("\n".join(table), encoding="ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", required=True, type=Path)
    parser.add_argument("--abi", required=True)
    parser.add_argument("--catalog", type=Path, default=CATALOG)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    try:
        cpu, entries, regions, objects = read_bundle(args.input, args.abi, llvm_operation_names(read_catalog(args.catalog)))
        if args.output is not None:
            write_build_inputs(args.output, cpu, entries, regions, objects)
        else:
            print(len(objects))
    except (OSError, ValueError) as error:
        parser.exit(1, f"{args.input}: {error}\n")


if __name__ == "__main__":
    main()
